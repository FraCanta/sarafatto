<?php
/** Shared catalog product card. */
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

$product_id = get_the_ID();
$args = isset( $args ) && is_array( $args ) ? $args : array();
$flags      = sarafatto_get_product_flags( $product_id );
$price      = sarafatto_format_price( sarafatto_get_product_price( $product_id ) );
$thumbnail_id = get_post_thumbnail_id( $product_id );
if ( ! $thumbnail_id && ! empty( $args['use_gallery_fallback'] ) && function_exists( 'sarafatto_sanitize_gallery_ids' ) ) {
	$gallery_ids = sarafatto_sanitize_gallery_ids( get_post_meta( $product_id, 'sarafatto_gallery', true ) );
	$thumbnail_id = $gallery_ids ? absint( $gallery_ids[0] ) : 0;
}
$image_alt    = $thumbnail_id ? get_post_meta( $thumbnail_id, '_wp_attachment_image_alt', true ) : '';
if ( '' === trim( (string) $image_alt ) ) {
	$image_alt = get_the_title( $product_id );
}
?>
<li class="product-card">
	<a class="product-card__link" href="<?php the_permalink(); ?>">
		<span class="product-card__media">
			<?php if ( $thumbnail_id ) : ?>
				<?php echo wp_get_attachment_image( $thumbnail_id, 'large', false, array( 'class' => 'product-card__image', 'alt' => $image_alt, 'loading' => 'lazy', 'decoding' => 'async' ) ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by wp_get_attachment_image(). ?>
			<?php else : ?>
				<span class="product-card__placeholder" aria-hidden="true"></span>
			<?php endif; ?>
			<?php if ( $flags['is_sold_out'] ) : ?>
				<span class="product-card__badge product-card__badge--sold-out"><?php echo esc_html( sarafatto_theme_label( 'Esaurito', 'Sold out' ) ); ?></span>
			<?php elseif ( $flags['is_new'] ) : ?>
				<span class="product-card__badge"><?php echo esc_html( sarafatto_theme_label( 'Novità', 'New' ) ); ?></span>
			<?php endif; ?>
		</span>
		<span class="product-card__details"><span class="product-card__name"><?php the_title(); ?><span class="product-card__arrow" aria-hidden="true">↗</span></span><?php if ( $price ) : ?><span class="product-card__price"><?php echo esc_html( $price ); ?></span><?php endif; ?></span>
	</a>
</li>
