<?php
/** Shared editorial hero for internal pages. */
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

$title           = isset( $args['title'] ) && is_string( $args['title'] ) ? trim( $args['title'] ) : '';
$breadcrumbs     = isset( $args['breadcrumbs'] ) && is_array( $args['breadcrumbs'] ) ? $args['breadcrumbs'] : array();
$description_html = isset( $args['description_html'] ) && is_string( $args['description_html'] ) ? $args['description_html'] : '';
$cta             = isset( $args['cta'] ) && is_array( $args['cta'] ) ? $args['cta'] : array();
$modifier_class  = isset( $args['class'] ) && is_string( $args['class'] ) ? sanitize_html_class( $args['class'] ) : '';
$contact_marker  = ! empty( $args['contact_marker'] );
$title_id        = 'standard-page-hero-title';

if ( '' === $title ) {
	return;
}

$title_label = wp_strip_all_tags( $title );
?>
<section class="standard-page-hero product-archive-hero<?php echo $modifier_class ? ' ' . esc_attr( $modifier_class ) : ''; ?>" data-standard-page-hero<?php echo $contact_marker ? ' data-contact-hero' : ''; ?> aria-labelledby="<?php echo esc_attr( $title_id ); ?>">
	<svg class="product-archive-hero__shape" viewBox="0 0 1440 820" preserveAspectRatio="none" aria-hidden="true" focusable="false">
		<path data-standard-page-hero-curve d="M0 0H1440V680 C1080 840 360 840 0 680Z" />
	</svg>
	<div class="product-archive-hero__content" data-standard-page-hero-content>
		<h1 class="product-archive-hero__title" id="<?php echo esc_attr( $title_id ); ?>">
			<span class="product-archive-hero__track" aria-hidden="true">
				<?php for ( $copy = 0; $copy < 2; $copy++ ) : ?>
					<span class="product-archive-hero__group">
						<?php for ( $item = 0; $item < 4; $item++ ) : ?>
							<span><?php echo esc_html( $title_label ); ?></span><span class="product-archive-hero__asterisk" aria-hidden="true">*</span>
						<?php endfor; ?>
					</span>
				<?php endfor; ?>
			</span>
			<span class="screen-reader-text"><?php echo esc_html( $title_label ); ?></span>
		</h1>
		<?php if ( $breadcrumbs ) : ?>
			<nav class="product-archive-hero__breadcrumb" aria-label="<?php echo esc_attr( sarafatto_theme_label( 'Percorso di navigazione', 'Breadcrumb' ) ); ?>">
				<?php foreach ( $breadcrumbs as $index => $item ) : ?>
					<?php if ( $index > 0 ) : ?><span aria-hidden="true">›</span><?php endif; ?>
					<?php if ( ! empty( $item['url'] ) ) : ?>
						<a href="<?php echo esc_url( $item['url'] ); ?>"><?php echo esc_html( $item['label'] ?? '' ); ?></a>
					<?php else : ?>
						<span aria-current="page"><?php echo esc_html( $item['label'] ?? '' ); ?></span>
					<?php endif; ?>
				<?php endforeach; ?>
			</nav>
		<?php endif; ?>
		<?php if ( '' !== trim( wp_strip_all_tags( $description_html ) ) ) : ?>
			<div class="standard-page-hero__description"><?php echo $description_html; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Content is generated by the_content() or sanitized with wp_kses_post(). ?></div>
		<?php endif; ?>
		<?php if ( ! empty( $cta['url'] ) && ! empty( $cta['label'] ) ) : ?>
			<a class="button button--primary button--lg standard-page-hero__cta<?php echo ! empty( $cta['class'] ) ? ' ' . esc_attr( sanitize_html_class( $cta['class'] ) ) : ''; ?>" href="<?php echo esc_url( $cta['url'] ); ?>">
				<span class="button__label"><?php echo esc_html( $cta['label'] ); ?></span>
				<svg class="button__icon button__icon--trailing standard-page-hero__arrow" viewBox="0 0 24 24" aria-hidden="true" focusable="false"><path d="M12 4v15m-7-7 7 7 7-7" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round" stroke-width="2" /></svg>
			</a>
		<?php endif; ?>
	</div>
</section>
