<?php
/** Shared image-led promotion for the Products mega menu and mobile menu. */
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

$promo   = isset( $args['promo'] ) && is_array( $args['promo'] ) ? $args['promo'] : sarafatto_get_menu_promo_banner();
$context = isset( $args['context'] ) && 'mobile' === $args['context'] ? 'mobile' : 'desktop';
$image_id = absint( $promo['image_id'] ?? 0 );
$image_alt = $image_id ? trim( (string) get_post_meta( $image_id, '_wp_attachment_image_alt', true ) ) : '';
?>
<article class="menu-promo menu-promo--<?php echo esc_attr( $context ); ?> menu-promo--<?php echo esc_attr( sanitize_html_class( $promo['type'] ?? 'shipping' ) ); ?><?php echo $image_id ? '' : ' menu-promo--no-image'; ?>" aria-label="<?php echo esc_attr( $promo['eyebrow'] ?? '' ); ?>">
	<?php if ( $image_id ) : ?>
		<figure class="menu-promo__media" aria-hidden="true">
			<?php $promo_srcset_limit = static function () { return 1024; }; add_filter( 'max_srcset_image_width', $promo_srcset_limit, 10, 0 ); ?>
			<?php echo wp_get_attachment_image( $image_id, 'large', false, array( 'alt' => $image_alt, 'loading' => 'lazy', 'decoding' => 'async' ) ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by wp_get_attachment_image(). ?>
			<?php remove_filter( 'max_srcset_image_width', $promo_srcset_limit, 10 ); ?>
		</figure>
	<?php endif; ?>
	<div class="menu-promo__content">
		<p class="menu-promo__eyebrow"><?php echo esc_html( $promo['eyebrow'] ?? '' ); ?></p>
		<h2 class="menu-promo__title"><?php echo esc_html( $promo['title'] ?? '' ); ?></h2>
		<?php if ( ! empty( $promo['text'] ) ) : ?>
			<p class="menu-promo__text"><?php echo esc_html( $promo['text'] ); ?></p>
		<?php endif; ?>
		<?php if ( ! empty( $promo['url'] ) && ! empty( $promo['label'] ) ) : ?>
			<?php get_template_part( 'template-parts/components/button', null, array( 'label' => $promo['label'], 'href' => $promo['url'], 'variant' => 'secondary', 'size' => 'md', 'icon' => 'arrow-right', 'icon_position' => 'after', 'class' => 'menu-promo__cta' ) ); ?>
		<?php endif; ?>
	</div>
</article>
