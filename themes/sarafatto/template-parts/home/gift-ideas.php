<?php
/** Compact current-language gift ideas, linked to populated taxonomy archives. */
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

$args  = isset( $args ) && is_array( $args ) ? $args : array();
$ideas = isset( $args['ideas'] ) && is_array( $args['ideas'] ) ? $args['ideas'] : array();
if ( ! $ideas ) {
	return;
}
?>
<section class="home-ideas" aria-labelledby="home-ideas-title">
	<div class="home-container">
		<header class="home-ideas__intro">
			<h2 class="home-section-title" id="home-ideas-title"><?php echo esc_html( sarafatto_theme_label( 'Idee regalo', 'Gift ideas' ) ); ?></h2>
		</header>
		<ul class="home-ideas__list home-ideas__list--count-<?php echo esc_attr( count( $ideas ) ); ?>">
			<?php foreach ( $ideas as $idea ) : ?>
				<li class="home-ideas__item">
					<a class="home-ideas__link" href="<?php echo esc_url( $idea['url'] ); ?>">
						<span class="home-ideas__media" aria-hidden="true">
							<?php if ( ! empty( $idea['image'] ) ) : ?>
								<?php echo wp_get_attachment_image( $idea['image'], 'medium_large', false, array( 'class' => 'home-ideas__image', 'alt' => '', 'loading' => 'lazy', 'decoding' => 'async' ) ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by wp_get_attachment_image(). ?>
							<?php elseif ( ! empty( $idea['icon'] ) && function_exists( 'sarafatto_get_term_icon_markup' ) ) : ?>
								<?php echo sarafatto_get_term_icon_markup( $idea['icon'], 'home-ideas__icon' ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated from the validated shared SVG icon set. ?>
							<?php else : ?>
								<span class="home-ideas__placeholder icon-[mdi--gift-outline]"></span>
							<?php endif; ?>
						</span>
						<span class="home-ideas__label">
							<?php echo esc_html( $idea['title'] ); ?>
							<span class="home-ideas__arrow" aria-hidden="true">↗</span>
						</span>
					</a>
				</li>
			<?php endforeach; ?>
		</ul>
	</div>
</section>
