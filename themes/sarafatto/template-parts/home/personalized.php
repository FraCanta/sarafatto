<?php
/** Home editorial service section for customisable products. */
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

$content = function_exists( 'sarafatto_get_home_personalized_content' )
	? sarafatto_get_home_personalized_content()
	: array();
$image_id = isset( $content['image_id'] ) ? absint( $content['image_id'] ) : 0;
$title    = isset( $content['title'] ) && is_string( $content['title'] ) ? trim( $content['title'] ) : '';
$title_lines = preg_split( '/\R/u', $title );
$title_lines = is_array( $title_lines ) ? array_values( array_filter( array_map( 'trim', $title_lines ), 'strlen' ) ) : array();

// Keep the intended two-line title even when the saved setting has no line break.
if ( 1 === count( $title_lines ) && preg_match( '/^(Hai qualcosa)\s+(da dire\?|to say\?)$/iu', $title_lines[0], $title_match ) ) {
	$title_lines = array( $title_match[1], $title_match[2] );
}
$page     = isset( $content['page'] ) ? $content['page'] : null;

if ( '' === $title ) {
	return;
}

$alt = sarafatto_theme_label( 'T-shirt bianca con il ricamo “Pensati ventenne”', 'White T-shirt embroidered with “Pensati ventenne”' );
$section_id = 'home-personalized-title';
?>
<section class="home-personalized" aria-labelledby="<?php echo esc_attr( $section_id ); ?>">
	<div class="home-personalized__inner">
		<div class="home-personalized__content">
			<h2 class="home-personalized__title home-section-title<?php echo count( $title_lines ) > 1 ? ' home-personalized__title--multiline' : ''; ?>" id="<?php echo esc_attr( $section_id ); ?>">
				<?php foreach ( $title_lines as $title_line ) : ?>
					<span><?php echo esc_html( $title_line ); ?></span>
				<?php endforeach; ?>
			</h2>
			<p class="home-personalized__lead"><?php echo nl2br( esc_html( $content['lead'] ) ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Newlines are converted to safe br tags after escaping. ?></p>
			<p class="home-personalized__body"><?php echo nl2br( esc_html( $content['body'] ) ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Newlines are converted to safe br tags after escaping. ?></p>
			<?php if ( $page instanceof WP_Post ) : ?>
				<?php
				get_template_part(
					'template-parts/components/button',
					null,
					array(
						'label'         => $content['cta'],
						'href'          => get_permalink( $page->ID ),
						'variant'       => 'primary',
						'size'          => 'lg',
						'trailing_icon' => 'arrow-right',
						'class'         => 'home-personalized__button',
					)
				);
				?>
			<?php endif; ?>
		</div>
		<figure class="home-personalized__media">
			<svg class="home-personalized__ribbon" viewBox="0 0 1536 864" preserveAspectRatio="none" aria-hidden="true" focusable="false">
				<defs>
					<linearGradient id="home-personalized-ribbon-gradient" x1="0" y1="0" x2="1" y2="1">
						<stop offset="0%" stop-color="#bcece7" />
						<stop offset="52%" stop-color="#82d8d1" />
						<stop offset="100%" stop-color="#54bdb5" />
					</linearGradient>
					<mask id="home-personalized-ribbon-shirt-mask" maskUnits="userSpaceOnUse" x="0" y="0" width="1536" height="864">
						<rect width="1536" height="864" fill="#fff" />
						<!-- Interrompe il nastro sul profilo centrale della maglietta per simulare il passaggio dietro. -->
						<path d="M405 0 C490 24 520 98 601 139 C695 187 826 189 925 147 C1042 98 1166 55 1264 128 C1349 191 1358 326 1391 441 C1427 565 1454 706 1372 788 C1293 866 1139 851 1002 846 L494 846 C354 840 190 815 133 721 C77 629 151 479 207 373 C275 244 290 70 405 0 Z" fill="#000" />
					</mask>
				</defs>
				<g class="home-personalized__ribbon-track" data-personalized-ribbon-track mask="url(#home-personalized-ribbon-shirt-mask)">
					<path class="home-personalized__ribbon-band" d="M-90 302 C102 119 254 136 390 303 C526 471 648 469 785 274 C929 69 1071 122 1194 299 C1311 467 1428 444 1620 220 L1620 363 C1444 567 1305 592 1164 399 C1034 220 939 207 819 386 C653 632 492 600 344 418 C216 261 104 244 -90 452 Z" fill="url(#home-personalized-ribbon-gradient)" />
					<path class="home-personalized__ribbon-highlight" d="M-70 323 C111 163 249 171 374 321 C511 485 658 503 804 291 C935 101 1064 151 1174 319 C1294 502 1436 477 1590 286" />
				</g>
			</svg>
			<?php if ( $image_id && wp_attachment_is_image( $image_id ) ) : ?>
				<?php echo wp_get_attachment_image( $image_id, 'large', false, array( 'class' => 'home-personalized__image', 'alt' => $alt, 'sizes' => '(max-width: 63.999rem) 90vw, 50vw', 'loading' => 'lazy', 'decoding' => 'async' ) ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by wp_get_attachment_image(). ?>
			<?php else : ?>
				<span class="home-personalized__placeholder" aria-hidden="true"></span>
			<?php endif; ?>
		</figure>
	</div>
</section>
