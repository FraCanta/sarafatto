<?php
/** Asymmetric category mosaic using the category taxonomy and term imagery. */
if ( ! defined( 'ABSPATH' ) ) { exit; }
$args = isset( $args ) && is_array( $args ) ? $args : array();
$categories = isset( $args['categories'] ) && is_array( $args['categories'] ) ? array_slice( $args['categories'], 0, 4 ) : array();
if ( ! $categories ) { return; }
?>
<section class="home-category-mosaic" aria-labelledby="home-category-mosaic-title">
	<div class="home-container">
		<header class="home-category-mosaic__intro">
			<h2 class="home-section-title" id="home-category-mosaic-title"><?php echo esc_html( sarafatto_theme_label( 'Regalo da fare? Niente panico.', 'Need a gift? No worries.' ) ); ?></h2>
		</header>
<ul class="home-category-mosaic__grid home-category-mosaic__grid--count-<?php echo esc_attr( count( $categories ) ); ?>">
			<?php foreach ( $categories as $index => $category ) : ?>
				<?php $term = $category['term']; ?>
				<li class="home-category-mosaic__item home-category-mosaic__item--<?php echo esc_attr( $index + 1 ); ?><?php echo $category['image_id'] ? ' has-image' : ' is-placeholder'; ?>">
					<a class="home-category-mosaic__link" href="<?php echo esc_url( $category['url'] ); ?>">
						<?php if ( $category['image_id'] ) : ?>
							<?php echo wp_get_attachment_image( $category['image_id'], 'large', false, array( 'class' => 'home-category-mosaic__image', 'alt' => '', 'loading' => 'lazy', 'decoding' => 'async' ) ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by wp_get_attachment_image(). ?>
						<?php else : ?><span class="home-category-mosaic__placeholder icon-[mdi--shape-outline]" aria-hidden="true"></span><?php endif; ?>
						<span class="home-category-mosaic__label"><?php echo esc_html( $term->name ); ?></span>
						<span class="home-category-mosaic__arrow" aria-hidden="true">↗</span>
					</a>
				</li>
			<?php endforeach; ?>
		</ul>
	</div>
</section>
