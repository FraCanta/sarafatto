<?php
/** Home discoveries: editorial category links. */
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

$category_args = array(
	'taxonomy'   => 'sarafatto_categoria',
	'hide_empty' => false,
	'orderby'    => 'term_order',
	'order'      => 'ASC',
	'number'     => 0,
);
if ( function_exists( 'sarafatto_add_language_to_query_args' ) ) {
	$category_args = sarafatto_add_language_to_query_args( $category_args );
}

$queried_categories = get_terms( $category_args );
if ( is_wp_error( $queried_categories ) || ! is_array( $queried_categories ) ) {
	return;
}

$categories = array();
foreach ( $queried_categories as $category ) {
	if ( ! $category instanceof WP_Term || ! function_exists( 'sarafatto_get_category_image_id' ) ) {
		continue;
	}

	$image_id = sarafatto_get_category_image_id( $category->term_id );
	$term_url = get_term_link( $category );
	if ( ! $image_id || is_wp_error( $term_url ) ) {
		continue;
	}

	$categories[] = array(
		'term'     => $category,
		'image_id' => $image_id,
		'url'      => $term_url,
	);
	if ( count( $categories ) === 5 ) {
		break;
	}
}

$category_count = count( $categories );
$english = function_exists( 'sarafatto_get_current_language' ) && 0 === strpos( sarafatto_get_current_language(), 'en' );

$featured_args = array(
	'post_type'      => 'sarafatto_prodotto',
	'post_status'    => 'publish',
	'posts_per_page' => -1,
	'orderby'        => array( 'menu_order' => 'ASC', 'date' => 'DESC' ),
	'meta_query'     => array(
		array(
			'key'     => 'sarafatto_is_featured',
			'value'   => '1',
			'compare' => '=',
		),
	),
);
if ( function_exists( 'sarafatto_add_language_to_query_args' ) ) {
	$featured_args = sarafatto_add_language_to_query_args( $featured_args );
}
$featured_query = new WP_Query( $featured_args );
$featured_products = array();
foreach ( $featured_query->posts as $product ) {
	if ( ! has_post_thumbnail( $product ) ) {
		continue;
	}
	$featured_products[] = $product;
}
$featured_count = count( $featured_products );
$archive_url = get_post_type_archive_link( 'sarafatto_prodotto' );
?>
<section class="home-discoveries" aria-label="<?php echo esc_attr( sarafatto_theme_label( 'Scoperte e prodotti in evidenza', 'Discoveries and featured products' ) ); ?>">
	<div class="home-discoveries__inner">
		<?php if ( $categories ) : ?>
			<div class="home-discoveries__category-row">
				<header class="home-discoveries__heading">
					<h2 class="home-discoveries__heading-main" id="home-discoveries-title">
						<span class="home-discoveries__word"><?php echo esc_html( $english ? 'Little' : 'Piccole' ); ?></span>
						<span class="home-discoveries__word"><?php echo esc_html( $english ? 'big' : 'grandi' ); ?></span>
						<span class="home-discoveries__word"><?php echo esc_html( $english ? 'discoveries,' : 'scoperte,' ); ?></span>
					</h2>
					<p class="home-discoveries__handwritten">
						<span class="home-discoveries__handwritten-text"><?php echo esc_html( $english ? 'every day.' : 'ogni giorno.' ); ?></span>
					</p>
				</header>

				<ul class="home-discoveries__list home-discoveries__list--count-<?php echo esc_attr( $category_count ); ?>" aria-label="<?php echo esc_attr( $english ? 'Explore product categories' : 'Esplora le categorie prodotto' ); ?>">
					<?php foreach ( $categories as $item ) : ?>
						<?php
						$term = $item['term'];
						$category_label = sprintf( $english ? 'Explore the %s category' : 'Esplora la categoria %s', $term->name );
						?>
						<li class="home-discoveries__item">
							<a class="home-discoveries__link" href="<?php echo esc_url( $item['url'] ); ?>" aria-label="<?php echo esc_attr( $category_label ); ?>">
								<span class="home-discoveries__image-wrap">
									<?php echo wp_get_attachment_image( $item['image_id'], 'large', false, array( 'class' => 'home-discoveries__image', 'alt' => '', 'loading' => 'lazy', 'decoding' => 'async' ) ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- generated by wp_get_attachment_image(). ?>
								</span>
								<span class="home-discoveries__label"><?php echo esc_html( $term->name ); ?></span>
								<svg class="home-discoveries__category-arrow" viewBox="0 0 16 12" aria-hidden="true" focusable="false"><path d="M1 6h12m-4-4 4 4-4 4" /></svg>
							</a>
						</li>
					<?php endforeach; ?>
				</ul>
			</div>
		<?php endif; ?>

		<?php if ( $featured_products && $archive_url ) : ?>
			<section class="home-featured" aria-labelledby="home-featured-title">
				<div class="home-featured__intro">
					<h2 class="home-featured__title" id="home-featured-title"><span class="editorial-underline editorial-underline--02"><?php echo esc_html( sarafatto_theme_label( 'In evidenza', 'Featured' ) ); ?></span></h2>
					<p class="home-featured__copy"><?php echo esc_html( sarafatto_theme_label( 'Una selezione di oggetti che Sara ha scelto di mettere in primo piano. Non sono solo novità, ma piccole grandi certezze.', 'A selection of objects Sara has chosen to put in the spotlight. Not just new arrivals, but little things worth noticing.' ) ); ?></p>
					<?php
					get_template_part(
						'template-parts/components/button',
						null,
						array(
							'label'         => sarafatto_theme_label( 'Scopri tutti', 'Discover all' ),
							'href'          => $archive_url,
							'variant'       => 'secondary',
							'size'          => 'sm',
							'icon'          => 'arrow-right',
							'icon_position' => 'after',
							'class'         => 'home-featured__button',
						)
					);
					?>
				</div>
				<div class="home-featured__catalog">
					<?php if ( $featured_count > 4 ) : ?>
						<div class="home-featured__controls" aria-label="<?php echo esc_attr( sarafatto_theme_label( 'Navigazione prodotti in evidenza', 'Featured products navigation' ) ); ?>">
							<button class="home-featured__control" type="button" data-featured-scroll="prev" aria-label="<?php echo esc_attr( sarafatto_theme_label( 'Prodotti precedenti', 'Previous products' ) ); ?>"><span class="icon-[mdi--arrow-left]" aria-hidden="true"></span></button>
							<button class="home-featured__control" type="button" data-featured-scroll="next" aria-label="<?php echo esc_attr( sarafatto_theme_label( 'Prodotti successivi', 'Next products' ) ); ?>"><span class="icon-[mdi--arrow-right]" aria-hidden="true"></span></button>
						</div>
					<?php endif; ?>
					<ul class="home-featured__list home-featured__list--count-<?php echo esc_attr( min( 4, $featured_count ) ); ?><?php echo $featured_count > 4 ? ' home-featured__list--scrollable' : ''; ?>" data-featured-list aria-label="<?php echo esc_attr( sarafatto_theme_label( 'Prodotti in evidenza', 'Featured products' ) ); ?>">
						<?php foreach ( $featured_products as $product ) : ?>
							<?php
							$product_id = $product->ID;
							$price = function_exists( 'sarafatto_get_product_price' ) ? sarafatto_get_product_price( $product_id ) : '';
							$price = $price && function_exists( 'sarafatto_format_price' ) ? sarafatto_format_price( $price ) : '';
							?>
							<li class="home-featured__item">
								<a class="home-featured__link" href="<?php echo esc_url( get_permalink( $product_id ) ); ?>">
									<span class="home-featured__image-wrap"><?php echo get_the_post_thumbnail( $product_id, 'large', array( 'class' => 'home-featured__image', 'alt' => '', 'loading' => 'lazy', 'decoding' => 'async' ) ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- generated by get_the_post_thumbnail(). ?></span>
									<span class="home-featured__name"><?php echo esc_html( get_the_title( $product_id ) ); ?></span>
									<?php if ( $price ) : ?><span class="home-featured__price"><?php echo esc_html( $price ); ?></span><?php endif; ?>
								</a>
							</li>
						<?php endforeach; ?>
					</ul>
				</div>
			</section>
		<?php endif; ?>
	</div>
</section>
