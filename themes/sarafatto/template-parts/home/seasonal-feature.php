<?php
/** One editorial slot: the first active occasion, or the seasonal fallback campaign. */
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

$active_occasions = function_exists( 'sarafatto_get_active_occasions' ) ? sarafatto_get_active_occasions() : array();
$occasion         = $active_occasions ? reset( $active_occasions ) : null;
$occasion_image   = $occasion instanceof WP_Term ? absint( get_term_meta( $occasion->term_id, 'sarafatto_occasion_image', true ) ) : 0;
$occasion_title   = $occasion instanceof WP_Term ? get_term_meta( $occasion->term_id, 'sarafatto_occasion_title', true ) : '';
$occasion_intro   = $occasion instanceof WP_Term ? get_term_meta( $occasion->term_id, 'sarafatto_occasion_intro', true ) : '';
$is_occasion      = $occasion instanceof WP_Term;

if ( $is_occasion ) {
	$occasion_title = is_string( $occasion_title ) && '' !== trim( $occasion_title ) ? $occasion_title : $occasion->name;
	$occasion_intro = is_string( $occasion_intro ) ? trim( $occasion_intro ) : '';
	$url = get_term_link( $occasion );
	$url = is_wp_error( $url ) ? '' : $url;
} else {
	$page = function_exists( 'sarafatto_get_linked_page' ) ? sarafatto_get_linked_page( 'idee_regalo' ) : null;
	$url = $page instanceof WP_Post ? get_permalink( $page->ID ) : '';
}

$fallback_image = get_theme_file_uri( 'assets/images/home-autumn-banner.jpg' );
?>
<section class="home-seasonal-feature<?php echo $is_occasion ? ' home-seasonal-feature--occasion' : ' home-seasonal-feature--fallback'; ?>" aria-labelledby="home-seasonal-feature-title">
	<?php if ( $url ) : ?><a class="home-seasonal-feature__link" href="<?php echo esc_url( $url ); ?>" aria-label="<?php echo esc_attr( $is_occasion ? $occasion_title : sarafatto_theme_label( 'Calzettoni e copertina. Lasciatemi qui!', 'Warm socks and a blanket. Leave me here!' ) ); ?>"><?php endif; ?>
		<figure class="home-seasonal-feature__media<?php echo $is_occasion && ! $occasion_image ? ' is-placeholder' : ''; ?>">
			<?php if ( $is_occasion && $occasion_image && wp_attachment_is_image( $occasion_image ) ) : ?>
				<?php echo wp_get_attachment_image( $occasion_image, 'full', false, array( 'alt' => esc_attr( $occasion_title ), 'loading' => 'lazy', 'decoding' => 'async' ) ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by wp_get_attachment_image(). ?>
			<?php elseif ( $is_occasion ) : ?>
				<span class="home-seasonal-feature__empty-visual" aria-hidden="true"></span>
			<?php else : ?>
				<img src="<?php echo esc_url( $fallback_image ); ?>" alt="<?php echo esc_attr( sarafatto_theme_label( 'Calzettoni e copertina. Lasciatemi qui!', 'Warm socks and a blanket. Leave me here!' ) ); ?>" width="1672" height="941" loading="lazy" decoding="async">
			<?php endif; ?>
		</figure>
		<?php if ( $is_occasion ) : ?>
			<div class="home-seasonal-feature__panel">
				<div>
					<h2 class="home-seasonal-feature__title" id="home-seasonal-feature-title"><?php echo esc_html( $occasion_title ); ?></h2>
					<?php if ( '' !== $occasion_intro ) : ?><p class="home-seasonal-feature__copy"><?php echo esc_html( $occasion_intro ); ?></p><?php endif; ?>
				</div>
				<span class="home-seasonal-feature__cta"><?php echo esc_html( sarafatto_theme_label( 'Scopri l’occasione', 'Explore this occasion' ) ); ?><span class="home-seasonal-feature__arrow" aria-hidden="true">↗</span></span>
			</div>
		<?php else : ?>
			<h2 class="screen-reader-text" id="home-seasonal-feature-title"><?php echo esc_html( sarafatto_theme_label( 'Calzettoni e copertina. Lasciatemi qui!', 'Warm socks and a blanket. Leave me here!' ) ); ?></h2>
		<?php endif; ?>
	<?php if ( $url ) : ?></a><?php endif; ?>
</section>
