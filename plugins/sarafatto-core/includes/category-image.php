<?php
/** Editorial image metadata for product categories. */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

const SARAFATTO_CATEGORY_IMAGE_META_KEY = 'sarafatto_category_image_id';

/** Register the optional image as metadata owned by each individual term. */
function sarafatto_register_category_image_meta() {
	register_term_meta(
		'sarafatto_categoria',
		SARAFATTO_CATEGORY_IMAGE_META_KEY,
		array(
			'type'              => 'integer',
			'single'            => true,
			'sanitize_callback' => 'sarafatto_sanitize_term_image_id',
			'auth_callback'     => 'sarafatto_can_edit_term_meta',
		)
	);
}
add_action( 'init', 'sarafatto_register_category_image_meta', 20 );

/** Return a valid image attachment ID for a category, or zero. */
function sarafatto_get_category_image_id( $term_id ) {
	$term = get_term( absint( $term_id ), 'sarafatto_categoria' );
	if ( ! $term instanceof WP_Term ) {
		return 0;
	}

	return sarafatto_sanitize_term_image_id( get_term_meta( $term->term_id, SARAFATTO_CATEGORY_IMAGE_META_KEY, true ) );
}

/** Render the Media Library field on category creation and editing screens. */
function sarafatto_render_category_image_field( $term_id = 0, $show_label = true ) {
	$image_id = $term_id ? sarafatto_get_category_image_id( $term_id ) : 0;
	$image    = $image_id ? wp_get_attachment_image( $image_id, 'thumbnail', false, array( 'alt' => '' ) ) : '';
	$select_label = __( 'Seleziona immagine', 'sarafatto-core' );
	$replace_label = __( 'Sostituisci immagine', 'sarafatto-core' );

	wp_nonce_field( 'sarafatto_save_category_image', 'sarafatto_category_image_nonce' );
	?>
	<div class="<?php echo $show_label ? 'form-field ' : ''; ?>sarafatto-term-image-field sarafatto-category-image-field">
		<?php if ( $show_label ) : ?><label for="sarafatto-category-image-id"><?php esc_html_e( 'Immagine editoriale', 'sarafatto-core' ); ?></label><?php endif; ?>
		<input type="hidden" id="sarafatto-category-image-id" name="<?php echo esc_attr( SARAFATTO_CATEGORY_IMAGE_META_KEY ); ?>" value="<?php echo esc_attr( $image_id ); ?>">
		<div class="sarafatto-term-image-preview" aria-live="polite"><?php echo $image; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- generated by wp_get_attachment_image(). ?></div>
		<button type="button" class="button sarafatto-term-image-select" data-select-label="<?php echo esc_attr( $select_label ); ?>" data-replace-label="<?php echo esc_attr( $replace_label ); ?>"><?php echo esc_html( $image_id ? $replace_label : $select_label ); ?></button>
		<button type="button" class="button-link-delete sarafatto-term-image-remove" <?php echo $image_id ? '' : 'hidden'; ?>><?php esc_html_e( 'Rimuovi immagine', 'sarafatto-core' ); ?></button>
	</div>
	<?php
}

function sarafatto_render_category_image_add_field() {
	sarafatto_render_category_image_field();
}
add_action( 'sarafatto_categoria_add_form_fields', 'sarafatto_render_category_image_add_field' );

function sarafatto_render_category_image_edit_field( $term ) {
	?>
	<tr class="form-field">
		<th scope="row"><label for="sarafatto-category-image-id"><?php esc_html_e( 'Immagine editoriale', 'sarafatto-core' ); ?></label></th>
		<td><?php sarafatto_render_category_image_field( $term->term_id, false ); ?></td>
	</tr>
	<?php
}
add_action( 'sarafatto_categoria_edit_form_fields', 'sarafatto_render_category_image_edit_field' );

/** Save only a valid image ID; a submitted zero removes the optional metadata. */
function sarafatto_save_category_image_meta( $term_id ) {
	$nonce = isset( $_POST['sarafatto_category_image_nonce'] ) && is_scalar( $_POST['sarafatto_category_image_nonce'] )
		? sanitize_text_field( wp_unslash( $_POST['sarafatto_category_image_nonce'] ) )
		: '';
	if ( ! $nonce || ! wp_verify_nonce( $nonce, 'sarafatto_save_category_image' ) || ! current_user_can( 'manage_categories' ) ) {
		return;
	}

	if ( ! isset( $_POST[ SARAFATTO_CATEGORY_IMAGE_META_KEY ] ) || ! is_scalar( $_POST[ SARAFATTO_CATEGORY_IMAGE_META_KEY ] ) ) {
		return;
	}

	$image_id = absint( sanitize_text_field( wp_unslash( $_POST[ SARAFATTO_CATEGORY_IMAGE_META_KEY ] ) ) );
	if ( $image_id && ! wp_attachment_is_image( $image_id ) ) {
		return;
	}

	if ( $image_id ) {
		update_term_meta( $term_id, SARAFATTO_CATEGORY_IMAGE_META_KEY, $image_id );
	} else {
		delete_term_meta( $term_id, SARAFATTO_CATEGORY_IMAGE_META_KEY );
	}
}
add_action( 'created_sarafatto_categoria', 'sarafatto_save_category_image_meta' );
add_action( 'edited_sarafatto_categoria', 'sarafatto_save_category_image_meta' );

/** Show the editorial image as a compact thumbnail in the category list. */
function sarafatto_category_image_admin_column( $columns ) {
	$columns['sarafatto_category_image'] = __( 'Immagine', 'sarafatto-core' );
	return $columns;
}
add_filter( 'manage_edit-sarafatto_categoria_columns', 'sarafatto_category_image_admin_column' );

function sarafatto_render_category_image_admin_column( $content, $column_name, $term_id ) {
	if ( 'sarafatto_category_image' !== $column_name ) {
		return $content;
	}

	$image_id = sarafatto_get_category_image_id( $term_id );
	if ( ! $image_id ) {
		return '';
	}

	return wp_get_attachment_image(
		$image_id,
		'thumbnail',
		false,
		array(
			'alt'   => '',
			'class' => 'sarafatto-category-image-thumbnail',
		)
	);
}
add_filter( 'manage_sarafatto_categoria_custom_column', 'sarafatto_render_category_image_admin_column', 10, 3 );

/** Load the existing term image selector only on the product category screens. */
function sarafatto_enqueue_category_image_admin_assets() {
	$screen = get_current_screen();
	if ( ! $screen || 'sarafatto_categoria' !== $screen->taxonomy ) {
		return;
	}

	wp_enqueue_media();
	wp_enqueue_style( 'sarafatto-term-meta', SARAFATTO_CORE_URL . 'assets/css/term-meta.css', array(), SARAFATTO_CORE_VERSION );
	wp_enqueue_script( 'sarafatto-term-meta', SARAFATTO_CORE_URL . 'assets/js/term-meta.js', array( 'jquery' ), SARAFATTO_CORE_VERSION, true );
	wp_localize_script(
		'sarafatto-term-meta',
		'sarafattoTermMeta',
		array(
			'messages' => array(
				'selectImage' => __( 'Seleziona un’immagine editoriale', 'sarafatto-core' ),
				'useImage'    => __( 'Usa questa immagine', 'sarafatto-core' ),
			),
		)
	);
}
add_action( 'admin_enqueue_scripts', 'sarafatto_enqueue_category_image_admin_assets' );
